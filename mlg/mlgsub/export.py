"""A committed brain leaves the lab: the .mlgb file the Quest engine reads.

Layout (little endian), read by engine/mlg_core.c:

    "MLGB" u32 version
    u32 d_model, n_layers, n_heads, n_experts, top_k, ffn_mult, ctx, wtype (0 f32, 1 q8)
    f32 tok[256][d]  f32 pos[ctx][d]
    per layer: f32 ln1.w[d] ln1.b[d]; M qkv[3d][d]; M proj[d][d]; f32 ln2.w[d] ln2.b[d];
               f32 gate[E][d] (only when E > 1); per expert: M up[f*d][d]; M down[d][f*d]
    f32 ln.w[d] ln.b[d]

M is a matrix in the file's wtype: f32 rows, or q8 (f32 scale per row, then int8 rows),
so every weight row is read once per generated byte. Embeddings, norms and the gate
stay f32: they are small and the output layer reuses the byte embedding.
"""
import hashlib
import struct

import numpy as np
import torch

MAGIC, VERSION = b"MLGB", 1
F32, Q8 = 0, 1


def quantize_q8(w):
    """Per-row symmetric int8: w ~= scale[:, None] * q."""
    w = w.float()
    scale = w.abs().amax(1).clamp_min(1e-12) / 127.0
    q = torch.round(w / scale[:, None]).clamp(-127, 127).to(torch.int8)
    return scale, q


def dequantize_q8(scale, q):
    return scale[:, None] * q.float()


def _f32(fh, t):
    fh.write(np.ascontiguousarray(t.detach().float().cpu().numpy(), dtype="<f4").tobytes())


def _matrix(fh, t, wtype):
    if wtype == F32:
        _f32(fh, t)
    else:
        scale, q = quantize_q8(t)
        _f32(fh, scale)
        fh.write(np.ascontiguousarray(q.cpu().numpy(), dtype=np.int8).tobytes())


def as_deployed(state, g, wtype=Q8):
    """The weights exactly as the engine will see them (q8 rounding included),
    so the lab can measure what the Quest will actually run."""
    if wtype == F32:
        return {k: v.float().clone() for k, v in state.items()}
    out = {}
    for k, v in state.items():
        matrix = k.endswith(("qkv.weight", "proj.weight", "up.weight", "down.weight"))
        out[k] = dequantize_q8(*quantize_q8(v)) if matrix else v.float().clone()
    return out


def write(path, state, g, wtype=Q8):
    """Write a brain's state_dict (Brain(g).state_dict() names) and return its sha256."""
    d, L, E = g["d_model"], g["n_layers"], g["n_experts"]
    with open(path, "wb") as fh:
        fh.write(MAGIC)
        fh.write(struct.pack("<9I", VERSION, d, L, g["n_heads"], E, g["top_k"], g["ffn_mult"], g["ctx"], wtype))
        _f32(fh, state["tok.weight"])
        _f32(fh, state["pos.weight"])
        for i in range(L):
            p = f"blocks.{i}."
            _f32(fh, state[p + "ln1.weight"])
            _f32(fh, state[p + "ln1.bias"])
            _matrix(fh, state[p + "qkv.weight"], wtype)
            _matrix(fh, state[p + "proj.weight"], wtype)
            _f32(fh, state[p + "ln2.weight"])
            _f32(fh, state[p + "ln2.bias"])
            if E > 1:
                _f32(fh, state[p + "moe.gate.weight"])
            for e in range(E):
                _matrix(fh, state[p + f"moe.experts.{e}.up.weight"], wtype)
                _matrix(fh, state[p + f"moe.experts.{e}.down.weight"], wtype)
        _f32(fh, state["ln.weight"])
        _f32(fh, state["ln.bias"])
    return sha256(path)


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for block in iter(lambda: fh.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()
